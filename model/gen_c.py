#!/usr/bin/env python3
"""Write the C tables of the CIM-MFCC front-end (hopcim/sw/mfcc_tables.h) and a test vector for
the R4b firmware (a GSC test clip with its golden lraw and int8 features from mfcc_int.py)."""
import os
import sys
import wave

import numpy as np

import cim_map as cm
import mfcc_int as mi

HERE = os.path.dirname(os.path.abspath(__file__))
SW = os.path.join(HERE, "..", "sw")
APP = os.path.expanduser("~/APlus_Project/planenest/hw/x-heep/sw/applications/hopcim_mfcc")


def carr(name, ctype, a, per_line=16, const=True):
    a = np.asarray(a)
    dims = "".join(f"[{d}]" for d in a.shape)
    flat = [str(int(v)) for v in a.ravel()]
    lines = [", ".join(flat[i:i + per_line]) for i in range(0, len(flat), per_line)]
    # tables: static const (rodata); test vectors: external linkage, so that GCC cannot move a
    # never-written array into rodata, which shares ram0 with the code
    q = "static const " if const else ""
    return f"{q}{ctype} {name}{dims} = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def tables_h():
    s = ["// Generated by hopcim/model/gen_c.py from mfcc_tables.npz -- do not edit.",
         "// Integer CIM-MFCC front-end (docs/MFCC_INT_SPEC.md); tile layout: model/cim_map.py.",
         "#ifndef HOPCIM_MFCC_TABLES_H_", "#define HOPCIM_MFCC_TABLES_H_", "#include <stdint.h>", ""]
    for k, v in dict(T_F1=cm.T_F1, T_F3=cm.T_F3, T_MEL00=cm.T_MEL00, T_MEL01=cm.T_MEL01, T_MEL11=cm.T_MEL11,
                     T_MEL12=cm.T_MEL12, T_D1=cm.T_D1, T_D2=cm.T_D2, MFCC_NTILES=8, B_F1=cm.B_F1, B_F3=cm.B_F3,
                     B_MEL=cm.B_MEL, B_DCT=cm.B_DCT, MFCC_K16=mi.K16, MFCC_LN2_Q16=mi.LN2_Q16,
                     MFCC_FLOOR_Q8=mi.FLOOR_Q8, MFCC_RQ_F=mi.RQ_F, MFCC_IN_ZP=mi.IN_ZP).items():
        s.append(f"#define {k} {v}")
    s.append(f"#define MFCC_RQ_M {mi.RQ_M}LL")
    s.append("")
    s.append(carr("MFCC_TILES", "int8_t", cm.TILES))
    s.append(carr("HANN_Q15", "int16_t", mi.HANN_Q15))
    s.append(carr("TWR_Q14", "int16_t", mi.TWr))
    s.append(carr("TWI_Q14", "int16_t", mi.TWi))
    s.append(carr("LOG2_LUT_Q8", "uint8_t", mi.LOG_LUT))
    s.append("#endif  // HOPCIM_MFCC_TABLES_H_")
    open(os.path.join(SW, "mfcc_tables.h"), "w").write("\n".join(s) + "\n")


def testvec_h(path, ded=False):
    """Test vector of the front-end firmware; ded=True: golden values of the B3 front-end (mfcc_ded)."""
    import mfcc_ded as md
    with wave.open(path, "rb") as w:
        x16 = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.int64)
    x = np.zeros(mi.NS, np.int64)
    x[:len(x16)] = x16
    lmx = mi.log2fix16(int(x16.max()))
    frame_lraw = md.frame_lraw if ded else mi.frame_lraw
    lraw = np.stack([frame_lraw(x[f * mi.HOP: f * mi.HOP + mi.WIN]) for f in range(mi.NFR)])
    feat = mi.finish(lraw, lmx)
    assert np.array_equal(feat.reshape(-1), (md.mfcc(x16) if ded else mi.cim_mfcc_int(x16)).reshape(-1))
    lraw32 = np.where(lraw == mi.ZERO, -(1 << 31), lraw)
    assert lraw32.min() >= -(1 << 31) and lraw32.max() < (1 << 31)
    s = [f"// Generated by hopcim/model/gen_c.py -- test clip {os.path.relpath(path, os.path.join(HERE, '..', '..'))}",
         "#include <stdint.h>", f"#define TV_LMX16 {lmx}", f"#define TV_NS {mi.NS}", "",
         "// not const: the test vector goes to the data bank (ram1); code and rodata share ram0",
         carr("TV_CLIP", "int16_t", x, const=False), carr("TV_LRAW", "int32_t", lraw32, 8, const=False),
         carr("TV_FEAT", "int8_t", feat.reshape(mi.NFR, mi.NMFCC), const=False)]
    os.makedirs(APP, exist_ok=True)
    open(os.path.join(APP, "testvec_ded.h" if ded else "testvec.h"), "w").write("\n".join(s) + "\n")
    print(f"test vector: {path} max {int(x16.max())} lmx16 {lmx}, zero-lraw entries {int((lraw == mi.ZERO).sum())}")


def svarr(name, width, a, signed=False, per_line=12):
    a = np.asarray(a).ravel()
    fmt = (lambda v: f"{'-' if v < 0 else ''}{width}'sd{abs(int(v))}") if signed else (lambda v: f"{width}'d{int(v)}")
    vals = [fmt(v) for v in a]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    t = "logic signed" if signed else "logic"
    return f"localparam {t} [{width - 1}:0] {name} [{len(a)}] = '{{\n    " + ",\n    ".join(lines) + "\n};\n"


def rtl_tables():
    """Constant tables of the hardware front-end (rtl/cim_fe.sv): Hann, twiddles, log2 table."""
    tw = (mi.TWr.astype(np.int64) & 0xFFFF) << 16 | (mi.TWi.astype(np.int64) & 0xFFFF)      # [k1][n2] -> {re, im}
    s = ["// Generated by hopcim/model/gen_c.py from mfcc_tables.npz -- do not edit.",
         "// Tables and constants of the hardware MFCC front-end (rtl/cim_fe.sv).", "",
         f"localparam int unsigned FE_T_F1 = {cm.T_F1}, FE_T_F3 = {cm.T_F3}, FE_T_MEL00 = {cm.T_MEL00}, "
         f"FE_T_MEL01 = {cm.T_MEL01}, FE_T_MEL11 = {cm.T_MEL11}, FE_T_MEL12 = {cm.T_MEL12};",
         f"localparam int unsigned FE_B_F1 = {cm.B_F1}, FE_B_F3 = {cm.B_F3}, FE_B_MEL = {cm.B_MEL};",
         f"localparam int FE_K16 = {mi.K16};", "",
         svarr("FE_HANN", 16, np.concatenate([mi.HANN_Q15, np.zeros(32, np.int64)])),   # padded to 512
         svarr("FE_TW", 32, tw.ravel()),
         svarr("FE_LOG_LUT", 8, mi.LOG_LUT)]
    open(os.path.join(HERE, "..", "rtl", "fe_tables.svh"), "w").write("\n".join(s) + "\n")


def ded_tables():
    """Tables of the B3 dedicated front-end (rtl/mfcc_ded.sv): Hann, radix-2 twiddles, sparse mel, log2."""
    import mfcc_ded as md
    tw = (md.TWD_R & 0x3FFFF) << 18 | (md.TWD_I & 0x3FFFF)                     # {re, im}, 18-bit Q16
    mel = np.zeros(128, np.int64)                                              # {m_lo[5:0], w_lo[7:0], w_hi[7:0]}
    for b in range(1, 128):
        nz = np.nonzero(mi.MELq[b])[0]
        if len(nz) == 0:
            continue
        m = int(nz[0])
        assert len(nz) <= 2 and (len(nz) == 1 or nz[1] == m + 1)
        w_hi = int(mi.MELq[b][m + 1]) if m + 1 < mi.NMEL else 0
        mel[b] = m << 16 | int(mi.MELq[b][m]) << 8 | w_hi
    assert int(sum(((mel >> 8) & 255).astype(bool)) + sum((mel & 255).astype(bool))) == int((mi.MELq != 0).sum())
    s = ["// Generated by hopcim/model/gen_c.py from mfcc_tables.npz -- do not edit.",
         "// Tables and constants of the B3 dedicated MFCC front-end (rtl/mfcc_ded.sv, model/mfcc_ded.py).", "",
         f"localparam int DED_K16 = {md.K16D};", "",
         svarr("DED_HANN", 16, np.concatenate([mi.HANN_Q15, np.zeros(32, np.int64)])),
         svarr("DED_TW", 36, tw),
         svarr("DED_MEL", 22, mel),
         svarr("DED_LOG_LUT", 8, mi.LOG_LUT)]
    open(os.path.join(HERE, "..", "rtl", "ded_tables.svh"), "w").write("\n".join(s) + "\n")


def wp_tables():
    """Constants of the hardware window path (rtl/cim_seq.sv, R5b): mfcc_int.finish in hardware."""
    s = ["// Generated by hopcim/model/gen_c.py from mfcc_int.py / cim_map.py -- do not edit.",
         "// Constants of the window path in the layer sequencer (rtl/cim_seq.sv, R5b).", "",
         f"localparam int unsigned WP_T_D1 = {cm.T_D1}, WP_T_D2 = {cm.T_D2}, WP_B_DCT = {cm.B_DCT};",
         f"localparam int unsigned WP_LN2_Q16 = {mi.LN2_Q16};          // ln 2, Q16",
         f"localparam int WP_FLOOR_Q8 = {mi.FLOOR_Q8};                  // ln(1e-6), Q8",
         f"localparam int unsigned WP_RQ_M = {mi.RQ_M}, WP_RQ_F = {mi.RQ_F};   // requantisation",
         f"localparam int unsigned WP_IN_ZP = {mi.IN_ZP};               // model input zero point"]
    open(os.path.join(HERE, "..", "rtl", "wp_tables.svh"), "w").write("\n".join(s) + "\n")


if __name__ == "__main__":
    tables_h()
    rtl_tables()
    ded_tables()
    wp_tables()
    clip = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "kws_gate", "data", "test", "yes",
                                                              "022cd682_nohash_0.wav")
    testvec_h(os.path.abspath(clip))
    testvec_h(os.path.abspath(clip), ded=True)
