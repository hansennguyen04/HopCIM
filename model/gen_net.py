#!/usr/bin/env python3
"""Write the C tables of the DS-CNN on the CIM (hopcim/sw/dscnn_tables.h: compact int8 weights,
biases and TFLite requantisation constants; the firmware builds the 61 CIM tiles from them) and a
test vector for the network firmware (sw/applications/hopcim_net/netvec.h: int8 features of 20
GSC test clips, one class at a time, with their golden logits from dscnn_int.forward)."""
import glob
import os
import wave

import numpy as np

import cim_net_map as cnm
import dscnn_int as d
import mfcc_int as mi
from gen_c import carr

HERE = os.path.dirname(os.path.abspath(__file__))
SW = os.path.join(HERE, "..", "sw")
APP = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sw", "applications", "hopcim_net")  # linked into X-HEEP by xheep/setup.sh
TEST = os.path.join(HERE, "..", "..", "kws_gate", "data", "test")
LABELS = ["down", "go", "left", "no", "off", "on", "right", "stop", "up", "yes", "_silence_", "_unknown_"]


def tables_h():
    P = d.P
    w_conv1 = P["L0_w"][:, :, :, 0].reshape(64, 40)                               # [oc][4 fy + fx]
    w_dw = np.stack([P[f"L{1 + 2 * l}_w"][0].reshape(9, 64).T for l in range(4)])  # [l][c][3 fy + fx]
    w_pw = np.stack([P[f"L{2 + 2 * l}_w"][:, 0, 0, :] for l in range(4)])         # [l][oc][ic]
    bias = np.zeros((10, 64), np.int64)
    qm = np.zeros((10, 64), np.int64)
    sh = np.zeros((10, 64), np.int64)
    for L in range(10):
        n = len(P[f"L{L}_b"])
        bias[L, :n] = P[f"L{L}_b"]
        qm[L, :n] = P[f"L{L}_q"] if len(P[f"L{L}_q"]) == n else P[f"L{L}_q"][0]
        sh[L, :n] = P[f"L{L}_sh"] if len(P[f"L{L}_sh"]) == n else P[f"L{L}_sh"][0]
    s = ["// Generated by hopcim/model/gen_net.py from the MLPerf Tiny int8 DS-CNN -- do not edit.",
         "// Integer semantics: model/dscnn_int.py (TFLite reference kernels); tiles: model/cim_net_map.py.",
         "#ifndef HOPCIM_DSCNN_TABLES_H_", "#define HOPCIM_DSCNN_TABLES_H_", "#include <stdint.h>", "",
         f"#define DS_ZIN0 {int(P['L0_zin'])}           // conv1 input zero point (the MFCC features)",
         f"#define DS_ZACT ({int(P['L1_zin'])})        // zero point of every other activation",
         f"#define DS_ZFC {int(P['L9_zout'])}             // logits zero point",
         f"#define DS_XB {cnm.XB}              // CIM input width of every network pass",
         f"#define DS_T_CONV1 {cnm.T_CONV1}",
         "#define DS_T_DW(l) (12 + 14 * (l))",
         "#define DS_T_PW(l) (22 + 14 * (l))",
         f"#define DS_T_FC {cnm.T_FC}", "",
         "// layer index L: 0 conv1, 1 + 2l depthwise l, 2 + 2l pointwise l, 9 fully connected (12 outputs)",
         carr("DS_W_CONV1", "int8_t", w_conv1),
         carr("DS_W_DW", "int8_t", w_dw, 9),
         carr("DS_W_PW", "int8_t", w_pw),
         carr("DS_W_FC", "int8_t", P["L9_w"]),
         carr("DS_BIAS", "int32_t", bias, 8),
         carr("DS_QM", "int32_t", qm, 8),
         carr("DS_SH", "int8_t", sh),
         "#endif  // HOPCIM_DSCNN_TABLES_H_"]
    open(os.path.join(SW, "dscnn_tables.h"), "w").write("\n".join(s) + "\n")
    # the firmware's tile construction must reproduce the mapping model's tiles
    t = np.zeros((128, 64, 16), np.int64)
    for j in range(4):
        t[cnm.T_CONV1 + j, :40, :] = w_conv1[16 * j: 16 * j + 16].T
    for l in range(4):
        for c in range(64):
            g, n = divmod(c, 7)
            t[cnm.t_dw(l) + g, 7 * np.arange(9) + n, n] = w_dw[l, c]
        for j in range(4):
            t[cnm.t_pw(l) + j] = w_pw[l, 16 * j: 16 * j + 16].T
    t[cnm.T_FC, :, :12] = P["L9_w"].T
    assert np.array_equal(t, cnm.TILES.astype(np.int64)), "C tile construction differs from cim_net_map"


def clips(n=20):
    """n GSC test clips spread over the 12 classes: [(int8 features [49, 10], label)]."""
    files = []
    for li, lab in enumerate(LABELS):
        files += [(p, li) for p in sorted(glob.glob(os.path.join(TEST, lab, "*.wav")))]
    out = []
    for p, li in files[::len(files) // n][:n]:
        with wave.open(p, "rb") as w:
            x16 = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.int64)
        out.append((mi.cim_mfcc_int(x16).reshape(49, 10), li))
    return out


def netvec_h(n=20):
    feats, logits, labels = [], [], []
    for q, li in clips(n):
        y = d.forward(q)
        assert np.array_equal(y, cnm.forward_mapped(q))
        feats.append(q); logits.append(y); labels.append(li)
    s = ["// Generated by hopcim/model/gen_net.py -- integer CIM-MFCC features of GSC test clips and the",
         "// golden int8 logits of the DS-CNN (model/dscnn_int.py, = TFLite reference kernels).",
         "#include <stdint.h>", f"#define NV_N {n}", "",
         carr("NV_FEAT", "int8_t", np.stack(feats)),
         carr("NV_LOGITS", "int8_t", np.stack(logits)),
         carr("NV_LABEL", "uint8_t", np.array(labels))]
    os.makedirs(APP, exist_ok=True)
    open(os.path.join(APP, "netvec.h"), "w").write("\n".join(s) + "\n")
    pred = [int(np.argmax(y)) for y in logits]
    print(f"netvec: {n} clips, labels {labels}, predictions {pred}, correct {sum(p == l for p, l in zip(pred, labels))}")


if __name__ == "__main__":
    tables_h()
    netvec_h()
