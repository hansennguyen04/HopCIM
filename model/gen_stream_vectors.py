#!/usr/bin/env python3
"""Test vectors for the streaming window path (R5b), for tb_cim_stream: a 3-s stream of GSC
speech (netvec clips 2, 17, 9: "left", silence, "on"; 150 hops, 101 decisions, 24 of them right
after a change of the window maximum) and its golden values, per front-end, in
hopcim/tb/stream_vec_{cim,ded}/:
  samples.hex  the int16 stream
  hops.hex     per hop: lmx16, recomputed-all flag, window maximum (model/stream_int.py)
  feat.hex     per decision: the window's int8 features [49][10] in window order
  logits.hex   per decision: golden int8 logits (dscnn_int.forward)
  meta.hex     number of hops, number of decisions, class of each decision
and tb/stream_vec_cim/log2.hex: log2fix16(max(v, 1)) for every v = 0..32767 (the hardware's
log2fix16 is checked exhaustively).
Also sw/applications/hopcim_stream/streamvec.h for the firmware: the first 2 s of the stream
(100 hops, 51 decisions) and its golden values (lmx16 and the recompute flag per hop; logits and
class per decision for both front-ends).
Every decision's features are asserted equal to the per-window reference first."""
import os

import numpy as np

import dscnn_int as d
from gen_c import carr
import mfcc_int as mi
import stream_int as si

HERE = os.path.dirname(os.path.abspath(__file__))
STREAM_CLIPS = (2, 17, 9)
FW_HOPS = 100                                       # firmware: the first 2 s
APP = os.path.expanduser("~/APlus_Project/planenest/hw/x-heep/sw/applications/hopcim_stream")


def stream():
    x20 = si.speech_stream(20)
    return np.concatenate([x20[16000 * i: 16000 * (i + 1)] for i in STREAM_CLIPS])


def write(path, vals, width):
    with open(path, "w") as f:
        f.write("\n".join(f"{int(v) & ((1 << 4 * width) - 1):0{width}x}" for v in vals) + "\n")


def streamvec_h(x, golden):
    """golden[ded] = (hops, logits, classes) of the full stream; the firmware gets the first 2 s."""
    nd = FW_HOPS - si.NROW
    hops = golden[False][0]
    s = ["// Generated by hopcim/model/gen_stream_vectors.py -- R5b streaming test: the first 2 s of",
         f"// a GSC speech stream (netvec clips {STREAM_CLIPS[0]}, {STREAM_CLIPS[1]}), golden values from model/stream_int.py.",
         "#include <stdint.h>", f"#define SV_HOPS {FW_HOPS}", f"#define SV_DEC {nd}", "",
         carr("SV_SAMPLES", "int16_t", x[:si.HOP * FW_HOPS], const=False),
         carr("SV_LMX", "uint32_t", [hops[3 * h] for h in range(FW_HOPS)], 8),
         carr("SV_ALL", "uint8_t", [hops[3 * h + 1] for h in range(FW_HOPS)]),
         carr("SV_LOGITS", "int8_t", np.stack(golden[False][1][:nd]), 12),
         carr("SV_CLASS", "uint8_t", golden[False][2][:nd]),
         carr("SV_LOGITS_DED", "int8_t", np.stack(golden[True][1][:nd]), 12),
         carr("SV_CLASS_DED", "uint8_t", golden[True][2][:nd])]
    os.makedirs(APP, exist_ok=True)
    with open(os.path.join(APP, "streamvec.h"), "w") as f:
        f.write("\n".join(s) + "\n")
    print(f"streamvec.h: {FW_HOPS} hops, {nd} decisions, {sum(hops[3 * h + 1] for h in range(si.NROW, FW_HOPS))} after a maximum change")


def main():
    write(os.path.join(HERE, "..", "tb", "stream_vec_cim", "log2.hex"),
          [mi.log2fix16(max(v, 1)) for v in range(32768)], 8)
    x = stream()
    golden = {}
    for ded in (False, True):
        out = os.path.join(HERE, "..", "tb", "stream_vec_" + ("ded" if ded else "cim"))
        os.makedirs(out, exist_ok=True)
        sm = si.StreamModel(ded)
        hops, feats, logits, classes = [], [], [], []
        for h in range(len(x) // si.HOP):
            n_all = sm.n_all
            f = sm.hop(x, h)
            hops += [sm.lmx, int(sm.n_all > n_all), int(sm.bmax.max())]
            if f is not None:
                assert np.array_equal(f, si.window_ref(x, h, ded))
                y = d.forward(f)
                feats.append(f)
                logits.append(y)
                classes.append(int(np.argmax(y)))
        write(os.path.join(out, "samples.hex"), x, 4)
        write(os.path.join(out, "hops.hex"), hops, 8)
        write(os.path.join(out, "feat.hex"), np.stack(feats).reshape(-1), 2)
        write(os.path.join(out, "logits.hex"), np.stack(logits).reshape(-1), 2)
        write(os.path.join(out, "meta.hex"), [len(x) // si.HOP, len(feats)] + classes, 8)
        golden[ded] = (hops, logits, classes)
        n_chg = sum(hops[3 * h + 1] for h in range(si.NROW, len(x) // si.HOP))
        print(f"[{'B3' if ded else 'cim_fe'}] {len(x) // si.HOP} hops, {len(feats)} decisions "
              f"({n_chg} after a maximum change), classes {classes[::10]}... -> {os.path.relpath(out)}")
    streamvec_h(x, golden)


if __name__ == "__main__":
    main()

