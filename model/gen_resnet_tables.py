#!/usr/bin/env python3
"""Tables for the firmware of hopcim_resnet: sw/resnet_tables.h (weights as row x output matrices, parameters, layer records)
and sw/applications/hopcim_resnet/resvec.h (images and golden logits): python gen_resnet_tables.py [images=20] [first image=0]"""
import os
import sys

import numpy as np

from gen_net2_vectors import CONV_L, OPS, descriptors
from resnet_int import cifar, forward
from resnet_map import Net

HERE = os.path.dirname(os.path.abspath(__file__))
nimg = int(sys.argv[1]) if len(sys.argv) > 1 else 20
first = int(sys.argv[2]) if len(sys.argv) > 2 else 0
net = Net()
P = net.P


def arr(name, vals, ctype="int8_t"):
    s = []
    for i in range(0, len(vals), 24):
        s.append(", ".join(str(int(v)) for v in vals[i:i + 24]))
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + ",\n".join(s) + "};\n"


out = ["// Generated by model/gen_resnet_tables.py from the published ResNet8 (docs/NET2_GATES.md). Do not edit.",
       "#ifndef HOPCIM_RESNET_TABLES_H_", "#define HOPCIM_RESNET_TABLES_H_", "#include <stdint.h>", ""]
meta = []
for L, n in enumerate(CONV_L):
    w = P[f"{n}.w"]
    m = (w.reshape(w.shape[0], -1).T if n != "fc" else w.T).astype(np.int8)          # rows x outputs
    b, R, C, rows, outs = net.base[n]
    assert m.shape == (rows, outs)
    out.append(arr(f"RN_W_{L}", m.reshape(-1)))
    meta.append((L, b, R, C, rows, outs))
out.append("typedef struct { const int8_t *w; uint8_t tile; uint8_t R; uint8_t C; uint16_t rows; uint16_t outs; } rn_layer_t;\n")
out.append("static const rn_layer_t RN_LAYER[10] = {\n" + ",\n".join(
    f"    {{RN_W_{L}, {b}, {R}, {C}, {rows}, {outs}}}" for L, b, R, C, rows, outs in meta) + "};\n")
bias, qm, e = [], [], []
for L, n in enumerate(CONV_L):
    for c in range(64):
        if c < len(P[f"{n}.b"]):
            bias.append(int(P[f"{n}.b"][c])); qm.append(int(P[f"{n}.q"][c])); e.append(int(-P[f"{n}.sh"][c]))
        else:
            bias.append(0); qm.append(0); e.append(0)
out.append(arr("RN_BIAS", bias, "int32_t") + arr("RN_QM", qm, "int32_t") + arr("RN_E", e, "int8_t"))
d = descriptors(net)
out.append("// layer records: 14 operations x 8 words\nstatic const uint32_t RN_DESC[14][8] = {\n" + ",\n".join(
    "    {" + ", ".join(f"0x{int(v) & 0xFFFFFFFF:08x}u" for v in w) + "}" for w in d) + "};\n")
out.append("#define RN_NOPS 14\n#endif")
open(os.path.join(HERE, "..", "sw", "resnet_tables.h"), "w").write("\n".join(out) + "\n")

x, lab = cifar(10000)
x = x[first:first + nimg]
v = forward(x, P)
vec = [f"// Generated by model/gen_resnet_tables.py: CIFAR-10 test images {first} .. {first + nimg - 1} (int8 = uint8 - 128), golden logits (model/resnet_int.py).",
       "#ifndef RESVEC_H_", "#define RESVEC_H_", "#include <stdint.h>", f"#define RV_N {nimg}",
       f"static uint8_t RV_IMG[RV_N][3072] = {{",
       ",\n".join("{" + ",".join(str(int(p) & 255) for p in x[i].reshape(-1)) + "}" for i in range(nimg)) + "};",
       f"static const int8_t RV_LOGITS[RV_N][10] = {{",
       ",\n".join("{" + ",".join(str(int(p)) for p in r) + "}" for r in v) + "};",
       f"static const uint8_t RV_LABEL[RV_N] = {{" + ",".join(str(int(l)) for l in lab[first:first + nimg]) + "};", "#endif"]
open(os.path.join(HERE, "..", "sw", "applications", "hopcim_resnet", "resvec.h"), "w").write("\n".join(vec) + "\n")
print("weights", sum(int(np.prod(P[f"{n}.w"].shape)) for n in CONV_L), "bytes;", nimg, "images; wrote sw/resnet_tables.h, resvec.h")
