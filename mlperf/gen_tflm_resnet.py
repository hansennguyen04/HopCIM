#!/usr/bin/env python3
"""Test vectors of the second network's CPU-only baseline (sw/applications/tflm_resnet, docs/NET2_GATES.md N6): CIFAR-10 test
images 0 .. n-1 as the model's int8 input (uint8 - 128), TensorFlow Lite Micro's 10 int8 outputs on the host (the tflite-micro
Python package at commit c0ecf6ff, the commit vendored into the firmware; the model ends in its softmax), HopCIM's golden logits
(model/resnet_int.py, the fully connected layer's int8 output, equal to TFLite's on all 10,000 images) and the labels.

  ~/venvs/mlperf_tiny/bin/python mlperf/gen_tflm_resnet.py [n=2]   (2 fit the 76-KiB data section next to the arena)
"""
import os
import sys

import numpy as np
from tflite_micro.python.tflite_micro import runtime

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "model"))
from resnet_int import MODEL, PARAMS, cifar, forward  # noqa: E402

n = int(sys.argv[1]) if len(sys.argv) > 1 else 2
x, lab = cifar(n)
P = np.load(PARAMS, allow_pickle=False)
logits = forward(x, P).astype(np.int64)
it = runtime.Interpreter.from_file(MODEL, arena_size=256 * 1024)
out = []
for i in range(n):
    it.set_input(x[i:i + 1], 0)
    it.invoke()
    out.append(it.get_output(0).reshape(-1).astype(np.int64))
out = np.array(out)
cls_t = out.argmax(1)
cls_h = logits.argmax(1)
print(f"{n} images: TFLM host classes {cls_t.tolist()}, HopCIM golden classes {cls_h.tolist()}, labels {lab.tolist()}")


def rows(a):
    return ",\n".join("{" + ",".join(str(int(v)) for v in r.reshape(-1)) + "}" for r in a)


h = ["// Generated by mlperf/gen_tflm_resnet.py: CIFAR-10 test images 0 .. %d (int8 = uint8 - 128); TFLite Micro's int8 outputs on the" % (n - 1),
     "// host (softmax, tflite-micro c0ecf6ff); HopCIM's golden logits (model/resnet_int.py, the fully connected layer's output); labels.",
     "#ifndef TFLM_RESNET_TVEC_H_", "#define TFLM_RESNET_TVEC_H_", "#include <stdint.h>", f"#define TV_N {n}",
     "// the images are in .data (RAM1), not .rodata: the code section has no room next to the model",
     "static int8_t TV_IMG[TV_N][3072] = {", rows(x) + "};",
     "static const int8_t TV_OUT[TV_N][10] = {", rows(out) + "};",
     "static const int8_t TV_LOGITS[TV_N][10] = {", rows(logits) + "};",
     "static const uint8_t TV_LABEL[TV_N] = {" + ",".join(str(int(v)) for v in lab) + "};", "#endif", ""]
open(os.path.join(HERE, "..", "sw", "applications", "tflm_resnet", "tvec.h"), "w").write("\n".join(h))
print("wrote sw/applications/tflm_resnet/tvec.h")
